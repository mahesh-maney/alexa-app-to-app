"""
alexa_complete_app_to_app — POST /api/v1/alexa/completeAppToApp

Stage 1 of the two-stage Alexa SMAPI account-linking flow.

Flow (SMAPI_LINKING_ENABLED=true):
  1.  Authenticate the caller via Cognito JWT (RS256, JWKS)
  2.  Validate the LWA state token (CSRF / replay protection):
        - must exist in DynamoDB
        - must belong to the authenticated userId
        - must not be expired
        - must have status PENDING (single-use)
  3.  Mark state USED immediately (before any network call — prevents replay)
  4.  Validate site ownership: siteId must exist for the authenticated userId
        in USER_DEVICE_MAPPING_TABLE
  5.  Exchange the LWA authorization code with Amazon:
        POST https://api.amazon.com/auth/o2/token
          grant_type    = authorization_code
          code          = <from Flutter>
          redirect_uri  = <LWA callback URI>
          client_id/secret = <from Secrets Manager>
          code_verifier = <from DDB session>
  6.  Store LWA access + refresh tokens (KMS-encrypted) in DynamoDB
  7.  Generate a backend PKCE verifier (64 random bytes, base64url) and S256 challenge
  8.  Generate a signed single-use OAuth state for the Cognito step:
        base64url(pkceTransactionId) + "." + base64url(HMAC-SHA256(signing_secret, pkceTransactionId))
  9.  Atomically acquire a per-user lock in alexa_pkce_sessions
        (prevents concurrent linking sessions for the same user)
  10. Store the PKCE transaction in alexa_pkce_sessions:
        {pkceTransactionId, userId, siteId, encryptedVerifier, oauthState,
         status=PENDING_COGNITO, createdAt, expiresAt}
  11. Return {linked: false, cognitoAuthUrl, pkceTransactionId} to Flutter

Feature flag: SMAPI_LINKING_ENABLED
  true  → Stage 1 flow above; Flutter must continue to Stage 2
  false → HTTP 503 LINKING_UNAVAILABLE (default; old false-success path removed)

Note: alexaLinked and isAlexaEnabled are NOT updated by Stage 1.
      These flags are set in Stage 2 after SMAPI confirms ENABLED + LINKED.

Error responses:
  400 — invalid/expired/already-used state, missing or malformed fields
  401 — unauthenticated
  403 — site not found or not owned by authenticated user
  409 — concurrent linking session already active for this user
  502 — LWA token exchange failed
  503 — LINKING_UNAVAILABLE (feature flag disabled)
"""
